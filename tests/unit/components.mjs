// What authors are told to write is what authors write: the attributes and classes in the Skill's
// documents, in the maintainers' markup reference (the component cards, quick-reference.md,
// visual-design.md, report-contract.md) and the classes the editor writes. A data-… that ends a word
// of hyphens is no attribute (a browser's --user-data-dir). A custom page's own attributes, on its
// boards and cards (data-card-id and the rest: shared/page-cards.mjs PAGE_ATTRIBUTES), are
// the page's, which no document's component describes. A name the kit sets that an author's own style
// selects on, in an attribute selector (`:root[data-doc-effective-theme="dark"]`, the theme a custom
// page's colors go by), is read, not written: a runtime name in `[…]` is no name told to be written.
