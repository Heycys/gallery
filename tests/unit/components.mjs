// Block spacing (docs/render.md, "Block spacing"): each distinct gap between a block and the text around
// it is one token of tokens.css, defined once with its value, read by the stylesheet of every block that
// takes it, and named with that value in the docs.
{
  const styles = path.join(projectRoot, "src", "render", "kit", "styles");
  const read = (name) => fs.readFileSync(path.join(styles, name), "utf8");
  const docs = fs.readFileSync(path.join(projectRoot, "docs", "render.md"), "utf8");
  const TAKEN_BY = {
    "--doc-component-gap": ["20px", ["flow.css", "callout.css", "columns.css", "figure.css", "state.css", "table.css"]],
    "--doc-block-gap": ["16px", ["flow.css", "highlight.css", "code.css", "sheets.css"]],
    "--doc-media-gap": ["14px", ["bookmark.css", "embed.css", "file.css", "image.css"]],
    "--doc-paragraph-gap": ["12px", ["flow.css", "details.css", "page.css"]],
    "--doc-group-gap": ["8px", ["details.css", "code.css", "math.css"]],
    "--doc-list-gap": ["5px", ["flow.css"]],
  };
  const tokenCss = read("tokens.css");
  for (const [token, [value, files]] of Object.entries(TAKEN_BY)) {
    assert.equal(tokenCss.split(`  ${token}: ${value};`).length, 2, `${token} is defined once, as ${value}`);
    for (const file of files) assert.ok(read(file).includes(`var(${token}`), `${file} reads ${token}`);
    assert.ok(docs.includes(`\`${token}\` ${value}`), `docs/render.md names ${token} as ${value}`);
  }
  assert.ok(!/one 20px (block )?rhythm/i.test(docs), "docs/render.md does not claim one rhythm for blocks of different gaps");
  // A disclosure's title row and a code block's, one design: the room above and below their words is one token.
  assert.equal(tokenCss.split("  --doc-block-title-padding: 5px;").length, 2, "--doc-block-title-padding is defined once, as 5px");
  for (const file of ["details.css", "code.css"]) assert.ok(!/padding: 8px/.test(read(file)) && read(file).includes("var(--doc-block-title-padding)"), `${file} pads its title row with --doc-block-title-padding`);
  assert.ok(docs.includes("5px above and below, `--doc-block-title-padding`"), "docs/render.md names the title row's padding");
}
