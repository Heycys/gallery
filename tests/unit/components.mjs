  const unitKinds = new Set(UNIT_KINDS.map(({ kind }) => kind));
  assert.ok(unitKinds.has(leadOf("highlight")), "a box's lead is a unit kind");
  // A diff is a whole block: its code card (data-doc-diff) is the editor's whole block, nothing in it a block.
  const { findUnits } = await import("../../src/editor/source.mjs");
